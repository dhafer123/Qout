"""Declarative base and shared columns for all ORM models."""

import uuid
from datetime import datetime
from typing import Any, ClassVar

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic constraint names, so Alembic can generate (and drop) them reliably.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class IdTimestampMixin:
    """UUID primary key plus database-managed `created_at` / `updated_at`.

    - `id` is generated by Postgres (`gen_random_uuid()`).
    - `created_at` and `updated_at` start as the transaction time (`now()`), so they are
      equal on insert.
    - `updated_at` becomes the wall-clock time (`clock_timestamp()`) on every ORM update,
      so it moves forward even within the transaction that created the row.
    - Server-generated values are fetched right after INSERT/UPDATE (`eager_defaults`),
      so reading them never triggers lazy IO in async code.
    """

    __mapper_args__: ClassVar[dict[str, Any]] = {"eager_defaults": True}

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, server_default=func.gen_random_uuid())
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.clock_timestamp()
    )
